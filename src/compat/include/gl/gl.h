// gl/gl.h — переходник к системному заголовку OpenGL.
//
// В Windows-версии заголовки OpenGL подключаются как <gl/gl.h> — каталог в
// нижнем регистре (fldviewdoc.h:13, tmcgltext.h:10). В Linux он называется GL.
// Править исходники win_src нельзя, поэтому здесь стоит переходник.
//
// Почему #include_next, а не #include <GL/gl.h>: проект собирается с диска,
// смонтированного без учёта регистра, и обычное подключение нашло бы этот же
// файл. #include_next продолжает поиск с каталога, следующего за тем, где
// найден текущий файл, и добирается до системного /usr/include/GL/gl.h.

#pragma once

#include_next <GL/gl.h>
